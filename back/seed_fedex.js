async function seed() {
    try {
        console.log("Conectando a base de datos...");
        await mongoose.connect(process.env.MONGODB_URI);
        console.log("Conectado. Limpiando colección de tarifarios...");
        await FedexTarifario.deleteMany({});

        const lines = rawData.trim().split('\n');
        const documents = [];

        for (let line of lines) {
            const parts = line.trim().split(/\s+/);
            if (parts.length >= 10) {
                const peso = parseFloat(parts[0]);
                const a = parseFloat(parts[1].replace(',', '.'));
                const b = parseFloat(parts[2].replace(',', '.'));
                const c = parseFloat(parts[3].replace(',', '.'));
                const d = parseFloat(parts[4].replace(',', '.'));
                const e = parseFloat(parts[5].replace(',', '.'));
                const f = parseFloat(parts[6].replace(',', '.'));
                const g = parseFloat(parts[7].replace(',', '.').replace('.', '')); // Ajuste para miles como 1.000,41 -> 1000.41
                const h = parseFloat(parts[8].replace(',', '.'));
                const i = parseFloat(parts[9].replace(',', '.'));

                // Helper para parsear miles y decimales
                const parseNum = (str) => {
                    // Limpiar puntos de miles y reemplazar coma por punto decimal
                    let cleaned = str.replace(/\./g, '').replace(',', '.');
                    return parseFloat(cleaned);
                };

                documents.push({
                    peso: peso,
                    A: parseNum(parts[1]),
                    B: parseNum(parts[2]),
                    C: parseNum(parts[3]),
                    D: parseNum(parts[4]),
                    E: parseNum(parts[5]),
                    F: parseNum(parts[6]),
                    G: parseNum(parts[7]),
                    H: parseNum(parts[8]),
                    I: parseNum(parts[9])
                });
            }
        }

        console.log(`Insertando ${documents.length} registros...`);
        await FedexTarifario.insertMany(documents);
        console.log("¡Seeding completado con éxito!");
        process.exit(0);
    } catch (error) {
        console.error("Error al sembrar base de datos:", error);
        process.exit(1);
    }
}

